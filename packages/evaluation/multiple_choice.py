"""Multiple-choice and log-likelihood evaluation engine.

Implements standard likelihood-based ranking (as used in MMLU, ARC, HellaSwag)
to rigorously evaluate language models without open-ended generation artifacts.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Any, Optional, Sequence

import torch
import torch.nn as nn
import torch.nn.functional as F


@dataclass
class ChoiceScore:
    """Log-likelihood score for a single candidate choice."""

    choice_index: int
    choice_text: str
    total_log_likelihood: float
    length_normalized_log_likelihood: float
    token_count: int


@dataclass
class MultipleChoiceResult:
    """Evaluation result for a multiple-choice probe."""

    prompt: str
    choices: list[str]
    correct_index: int
    predicted_index: int
    is_correct: bool
    scores: list[ChoiceScore]

    def to_dict(self) -> dict[str, Any]:
        return {
            "prompt": self.prompt,
            "choices": self.choices,
            "correct_index": self.correct_index,
            "predicted_index": self.predicted_index,
            "is_correct": self.is_correct,
            "scores": [
                {
                    "choice": s.choice_text,
                    "log_likelihood": round(s.total_log_likelihood, 4),
                    "norm_log_likelihood": round(s.length_normalized_log_likelihood, 4),
                }
                for s in self.scores
            ],
        }


class MultipleChoiceEvaluator:
    """Evaluates language models on multiple-choice questions using log-likelihood ranking."""

    def __init__(self, model: nn.Module, tokenizer: Any, device: Optional[torch.device] = None):
        self.model = model
        self.tokenizer = tokenizer
        if device is not None:
            self.device = device
        else:
            try:
                self.device = next(model.parameters()).device
            except StopIteration:
                self.device = torch.device("cpu")
        self.model.eval()

    def _encode(self, text: str) -> list[int]:
        """Encode text to a list of token IDs."""
        if hasattr(self.tokenizer, "encode"):
            tokens = self.tokenizer.encode(text)
            if hasattr(tokens, "ids"):
                return list(tokens.ids)
            elif isinstance(tokens, torch.Tensor):
                return tokens.view(-1).tolist()
            return list(tokens)
        raise AttributeError("Tokenizer must have an encode method.")

    @torch.no_grad()
    def score_choice(
        self,
        prompt_tokens: list[int],
        choice_tokens: list[int],
    ) -> ChoiceScore:
        """Compute the log-likelihood of choice tokens conditioned on prompt tokens.

        Math:
            log P(Choice | Prompt) = sum_{t=1}^{|Choice|} log P(choice_t | Prompt, choice_{<t})
        """
        if not choice_tokens:
            return ChoiceScore(
                choice_index=-1,
                choice_text="",
                total_log_likelihood=-1e9,
                length_normalized_log_likelihood=-1e9,
                token_count=0,
            )

        full_tokens = prompt_tokens + choice_tokens
        prompt_len = len(prompt_tokens)
        choice_len = len(choice_tokens)

        input_tensor = torch.tensor([full_tokens], dtype=torch.long, device=self.device)

        # Forward pass on full sequence
        output = self.model(input_tensor)
        logits = output[0] if isinstance(output, tuple) else output  # (1, total_len, vocab_size)

        # The prediction for full_tokens[t] is generated by logits[:, t-1, :]
        # Prompt tokens end at index prompt_len - 1.
        # So the first choice token (at index prompt_len) is predicted by logits at prompt_len - 1.
        start_logit_idx = prompt_len - 1
        end_logit_idx = prompt_len + choice_len - 1

        choice_logits = logits[0, start_logit_idx:end_logit_idx, :]  # (choice_len, vocab_size)
        log_probs = F.log_softmax(choice_logits, dim=-1)

        target_ids = torch.tensor(choice_tokens, dtype=torch.long, device=self.device)  # (choice_len,)
        token_log_probs = log_probs.gather(dim=-1, index=target_ids.unsqueeze(-1)).squeeze(-1)

        total_ll = token_log_probs.sum().item()
        norm_ll = total_ll / max(1, choice_len)

        return ChoiceScore(
            choice_index=-1,
            choice_text="",
            total_log_likelihood=total_ll,
            length_normalized_log_likelihood=norm_ll,
            token_count=choice_len,
        )

    def evaluate_question(
        self,
        prompt: str,
        choices: Sequence[str],
        correct_index: int,
        normalize_length: bool = True,
    ) -> MultipleChoiceResult:
        """Evaluate a single question across candidate choices and determine correctness."""
        prompt_tokens = self._encode(prompt)
        scores: list[ChoiceScore] = []

        best_score = -float("inf")
        best_idx = 0

        for idx, choice in enumerate(choices):
            choice_tokens = self._encode(choice)
            score = self.score_choice(prompt_tokens, choice_tokens)
            score.choice_index = idx
            score.choice_text = choice
            scores.append(score)

            metric = score.length_normalized_log_likelihood if normalize_length else score.total_log_likelihood
            if metric > best_score:
                best_score = metric
                best_idx = idx

        return MultipleChoiceResult(
            prompt=prompt,
            choices=list(choices),
            correct_index=correct_index,
            predicted_index=best_idx,
            is_correct=(best_idx == correct_index),
            scores=scores,
        )
